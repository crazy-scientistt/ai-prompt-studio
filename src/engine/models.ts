export const getModel = (id: string): ModelAdapter =>
  MODEL_ADAPTERS.find((m) => m.id === id) ?? MODEL_ADAPTERS[0]

/** Snap any requested duration to the closest length the model can generate. */
export const snapClipLength = (adapter: ModelAdapter, seconds: number): number =>
  adapter.clipLengths.reduce((best, l) =>
    Math.abs(l - seconds) < Math.abs(best - seconds) ? l : best,
  adapter.defaultClipLength)

