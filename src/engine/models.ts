export type TimestampStyle = 'seconds' | 'worded' | 'beats'
export type CameraStyle = 'operator' | 'motion-first' | 'directorial' | 'minimal'

export interface ModelAdapter {
  id: string
  name: string
  vendor: string
  providerHint: string
  maxChars: number
  idealChars: [number, number]
  supportsNegative: boolean
  timestampStyle: TimestampStyle
  cameraStyle: CameraStyle
  structure: 'linear-paragraphs' | 'structured-blocks' | 'shot-list' | 'single-flow'
  accent: string
  notes: string
  active: boolean
  compilerVersion: string
  /** Exact clip durations this model can generate in one pass (seconds). */
  clipLengths: number[]
  /** Pre-selected clip duration when the user doesn't choose. */
  defaultClipLength: number
}

